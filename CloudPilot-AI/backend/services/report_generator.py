import io
import csv
from typing import List, Dict, Any
from backend.models.schemas import ErrorPattern, RiskFactor, ActionableStep

class ReportGenerator:
    """Generates structured CSV, Markdown, and Executive Summaries."""

    @staticmethod
    def generate_patterns_csv(patterns: List[ErrorPattern]) -> str:
        output = io.StringIO()
        writer = csv.writer(output)
        writer.writerow(["Level", "Service", "Occurrences", "Normalized Signature", "Sample Message", "First Seen", "Last Seen"])
        for p in patterns:
            writer.writerow([
                p.level,
                p.service,
                p.count,
                p.signature,
                p.sample,
                p.first_seen or "",
                p.last_seen or ""
            ])
        return output.getvalue()

    @staticmethod
    def generate_incidents_csv(incidents: List[Dict[str, Any]]) -> str:
        output = io.StringIO()
        writer = csv.writer(output)
        writer.writerow(["Incident ID", "Title", "Severity", "Status", "Service", "Detected At", "Root Cause", "Action Recommendation"])
        for inc in incidents:
            writer.writerow([
                inc.get("incident_code"),
                inc.get("title"),
                inc.get("severity"),
                inc.get("status"),
                inc.get("service"),
                str(inc.get("detected_at")),
                inc.get("root_cause"),
                inc.get("recommendation")
            ])
        return output.getvalue()

    @staticmethod
    def generate_executive_markdown(
        filename: str,
        total_lines: int,
        level_counts: Dict[str, int],
        risk_score: int,
        risk_level: str,
        summary: str,
        root_cause: str,
        impact: str,
        factors: List[RiskFactor],
        recommendations: List[ActionableStep]
    ) -> str:
        md = f"""# CloudPilot AI — Executive Infrastructure Diagnostics Report

**Analyzed File:** `{filename}`  
**Evaluation Risk Score:** `{risk_score}/100` (`{risk_level}`)  
**Total Analyzed Events:** `{total_lines}`  
**Severity Breakdown:** CRITICAL: {level_counts.get('CRITICAL', 0)} | ERROR: {level_counts.get('ERROR', 0)} | WARNING: {level_counts.get('WARNING', 0)} | INFO: {level_counts.get('INFO', 0)}

---

## 1. Executive Summary
{summary}

## 2. Root Cause Analysis
{root_cause}

## 3. Operational & Business Impact
{impact}

## 4. Contributing Risk Breakdown
"""
        for f in factors:
            md += f"- **{f.factor}** (Weight: {f.weight}%, Impact: +{f.score_impact} pts): {f.explanation}\n"

        md += "\n## 5. Actionable Remediation Checklist\n"
        for r in recommendations:
            md += f"{r.step_number}. **{r.title}**  \n   *Command:* `{r.command_or_action}`  \n   *Rationale:* {r.rationale}\n\n"

        md += "---\n*Generated by CloudPilot AI Autonomous Diagnostics Suite*\n"
        return md

